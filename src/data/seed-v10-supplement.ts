import type { QuestionSeed } from './questions-seed';

/**
 * v10 보충 단원 증량 팩 — 교과서 외 보충 단원 11개를 단원당 60문항 이상으로 끌어올린다.
 *
 * 이 11개 단원이 미달이었던 까닭은 콘텐츠가 없어서가 아니라 OX 문항이 게임에
 * 출제되지 않기 때문이다(게임은 4지선다만 쓴다). 그래서 부족분을 전부 4지선다로 낸다.
 *
 * 원칙
 * - 발문은 기존 은행과 겹치지 않게 새로 쓴다(같은 학년·과목 안에서 발문이 겹치면 중복 폐기된다).
 * - 오답은 같은 단원에서 실제로 헷갈리는 개념으로 만든다. 엉뚱한 오답은 찍기를 쉽게 만든다.
 * - 정답이 둘이 될 수 있는 문항은 내지 않는다(띄어쓰기 허용 표기, 복수 표준어 주의).
 */

type Item = [text: string, answer: string, wrong: [string, string, string], why: string, difficulty?: number];

const out: QuestionSeed[] = [];

function unitPack(
  grade: number,
  subject: string,
  unit: string,
  unitCode: string | null,
  items: Item[]
) {
  for (const [text, answer, wrong, why, difficulty = 2] of items) {
    const opts = [answer, ...wrong];
    const r = text.length % 4;
    out.push({
      grade,
      subject,
      unit,
      unit_code: unitCode,
      question_type: 'multiple_choice',
      question_text: text,
      options: [...opts.slice(r), ...opts.slice(0, r)],
      correct_answer: answer,
      explanation: why,
      difficulty,
    });
  }
}

