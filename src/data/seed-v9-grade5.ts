/**
 * v9 5학년 보충 팩 — 감사에서 "출제 가능 문항 부족"으로 지목된 단원만 채운다.
 *
 * 대상은 두 갈래다.
 *  1) 보충·심화 묶음(어휘·속담·품사 등) — 원래 문항이 대부분 OX·주관식이라
 *     4지선다로 바꿔 낼 수 없어 실제 출제 가능 수가 0에 가까웠다.
 *  2) 5학년 도덕 4단원 — 단원당 20문항이 채 안 됐다.
 */

const out: QuestionSeed[] = [];

type Item = [text: string, answer: string, wrong: [string, string, string], why: string, difficulty?: number];

function pack(subject: string, unit: string, code: string | null, items: Item[]) {
  for (const [text, answer, wrong, why, difficulty = 2] of items) {
    const opts = [answer, ...wrong];
    const r = text.length % 4;
    out.push({
      grade: 5,
      subject,
      unit,
      unit_code: code,
      question_type: 'multiple_choice',
      question_text: text,
      options: [...opts.slice(r), ...opts.slice(0, r)],
      correct_answer: answer,
      explanation: why,
      difficulty,
    });
  }
}

/** 낱말 목록에서 "뜻 ↔ 낱말" 문항을 양방향으로 만든다 */
function wordPack(subject: string, unit: string, code: string | null, pairs: Array<[string, string]>, label = '낱말') {
  pairs.forEach(([word, meaning], i) => {
    const otherMeanings = pairs.filter((_, j) => j !== i).map(([, m]) => m);
    const otherWords = pairs.filter((_, j) => j !== i).map(([w]) => w);
    const rot = (arr: string[], by: number) => {
      const n = ((by % arr.length) + arr.length) % arr.length;
      return [...arr.slice(n), ...arr.slice(0, n)].slice(0, 3);
    };
    if (otherMeanings.length >= 3) {
      pack(subject, unit, code, [
        [`${label} '${word}'의 뜻으로 알맞은 것은?`, meaning, rot(otherMeanings, i) as [string, string, string], `'${word}'은(는) ${meaning}(이)라는 뜻입니다.`, 2],
      ]);
    }
    if (otherWords.length >= 3) {
      pack(subject, unit, code, [
        [`'${meaning}'을(를) 뜻하는 ${label}은?`, word, rot(otherWords, i + 1) as [string, string, string], `${meaning}을(를) 뜻하는 말은 '${word}'입니다.`, 2],
      ]);
    }
  });
}

