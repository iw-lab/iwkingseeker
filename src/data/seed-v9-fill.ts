/**
 * v9 마무리 보충 팩 — 감사(`npm run audit:questions`)가 마지막까지 지목한
 * "출제 가능 문항 60개 미만" 단원만 정확히 채운다.
 *
 * 이 단원들이 끝까지 얇았던 까닭은 기존 문항이 대부분 OX·주관식이라
 * 게임 화면에서 자동 출제되지 않았기 때문이다(전체 수는 있는데 낼 수가 없었다).
 * 그래서 여기서는 전부 4지선다로만 만든다.
 */

const out: QuestionSeed[] = [];

type Item = [text: string, answer: string, wrong: [string, string, string], why: string, difficulty?: number];

function pack(grade: number, subject: string, unit: string, code: string | null, items: Item[]) {
  for (const [text, answer, wrong, why, difficulty = 2] of items) {
    const opts = [answer, ...wrong];
    const r = text.length % 4;
    out.push({
      grade,
      subject,
      unit,
      unit_code: code,
      question_type: 'multiple_choice',
      question_text: text,
      options: [...opts.slice(r), ...opts.slice(0, r)],
      correct_answer: answer,
      explanation: why,
      difficulty,
    });
  }
}

/** 낱말 목록 → "뜻 ↔ 낱말" 양방향 문항 */
function wordPack(
  grade: number,
  subject: string,
  unit: string,
  code: string | null,
  pairs: Array<[string, string]>,
  label: string
) {
  const rot = (arr: string[], by: number): [string, string, string] => {
    const n = ((by % arr.length) + arr.length) % arr.length;
    return [...arr.slice(n), ...arr.slice(0, n)].slice(0, 3) as [string, string, string];
  };
  pairs.forEach(([word, meaning], i) => {
    const meanings = pairs.filter((_, j) => j !== i).map(([, m]) => m);
    const words = pairs.filter((_, j) => j !== i).map(([w]) => w);
    if (meanings.length >= 3) {
      pack(grade, subject, unit, code, [
        [`${label} '${word}'의 뜻으로 알맞은 것은?`, meaning, rot(meanings, i), `'${word}'은(는) ${meaning}(이)라는 뜻입니다.`, 2],
      ]);
    }
    if (words.length >= 3) {
      pack(grade, subject, unit, code, [
        [`'${meaning}'을(를) 뜻하는 ${label}은?`, word, rot(words, i + 1), `${meaning}을(를) 뜻하는 말은 '${word}'입니다.`, 2],
      ]);
    }
  });
}

